"""Generate skill/teardown-modding/references/api-index.md from the game's script_defs.lua and
the probe results in tools/probe/ (which side each function may be called from).

    python tools/gen_api_index.py ["C:/path/to/Teardown"]

Re-run after a game update (and re-run the probes: see tools/probe/README.md).
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = sys.argv[1] if len(sys.argv) > 1 else r"C:\Program Files (x86)\Steam\steamapps\common\Teardown"
P = os.path.join(ROOT, "tools", "probe")
src = open(os.path.join(GAME, "data", "script_defs.lua"), encoding="utf-8", errors="replace").read().splitlines()

def words(name):
    path = os.path.join(P, name)
    return set(open(path).read().split()) if os.path.exists(path) else set()

client_only = words("unavailable_server.txt")
server_only = words("unavailable_client.txt") | {"SetGravity", "SetTimeScale"}
internal, missing = set(), set()
for side in ("server", "client"):
    path = os.path.join(P, f"allcalls_{side}.json")
    if os.path.exists(path):
        d = json.load(open(path))[0]["data"]["returns"][0]
        internal |= set(d["internal"].split())
        missing |= set(d["missing"].split())
draw = os.path.join(P, "getters_draw.json")
if os.path.exists(draw):
    for row in json.load(open(draw))[0]["data"]["returns"][0].split("\n"):
        parts = row.split("|", 2)
        if len(parts) == 3 and "internal usage" in parts[2]:
            internal.add(parts[0])
missing = {m for m in missing if not m.startswith(("Ui", "GetDisplay"))}
skipped = set(json.load(open(os.path.join(P, "allcalls_skipped.json")))) if os.path.exists(os.path.join(P, "allcalls_skipped.json")) else set()

rows, section = [], "General"
for i, line in enumerate(src, 1):
    m = re.match(r"^function ([A-Za-z_][\w\.]*)\((.*)\)", line)
    if not m:
        continue
    name, params = m.group(1), m.group(2)
    if name in internal: flag = "internal"
    elif name in missing: flag = "missing"
    elif name.startswith("Ui"): flag = "draw"
    elif name in client_only: flag = "client"
    elif name in server_only: flag = "server"
    elif name.endswith("CPP") or name in skipped: flag = "untested"
    else: flag = ""
    rows.append((name, params, flag, i))

out = ["# Teardown API index",
       "",
       f"Generated by `tools/gen_api_index.py` from `data/script_defs.lua` (game 2.2.0, {len(rows)} functions) and the bridge probes.",
       "Signatures only: for the documentation and examples of a function read the line given here in",
       "`<Teardown>/data/script_defs.lua` (about 25 lines above the `function` line).",
       "",
       "Side column (measured, see quirks.md \"Wrong-side calls\"):",
       "",
       "- blank: callable from server and client code",
       "- `server`: server code only. From client code the engine stops the client half of the script",
       "- `client`: client code only. From server code the engine stops the server half of the script",
       "- `draw`: exists only inside `client.draw()` (nil everywhere else)",
       "- `internal`: raises \"function is only for internal usage\"; mods cannot use it",
       "- `missing`: documented but not present in the game",
       "- `untested`: not probed (destructive, session-level, or engine helper)",
       "",
       "| Function | Side | Line |", "|---|---|---|"]
for name, params, flag, line in rows:
    out.append(f"| `{name}({params})` | {flag} | {line} |")
dst = os.path.join(ROOT, "skill", "teardown-modding", "references", "api-index.md")
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
from collections import Counter
print(len(rows), Counter(r[2] or "both" for r in rows))
