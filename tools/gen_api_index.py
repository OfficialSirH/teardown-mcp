"""Generate skill/teardown-modding/references/api-index.md from the game's script_defs.lua and
the probe results in tools/probe/ (which side each function may be called from).

    python tools/gen_api_index.py ["C:/path/to/Teardown"]

Re-run after a game update (and re-run the probes: see tools/probe/README.md).
"""
import os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # -I leaves the script dir off sys.path
import api_sides

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = sys.argv[1] if len(sys.argv) > 1 else r"C:\Program Files (x86)\Steam\steamapps\common\Teardown"
src = open(os.path.join(GAME, "data", "script_defs.lua"), encoding="utf-8", errors="replace").read().splitlines()

side = api_sides.load()

# Which official doc file holds each function (tools/fetch_official_docs.py writes them; the
# folder is not in git, so without it the Doc column only says where to get it).
OFFICIAL = os.path.join(ROOT, "skill", "teardown-modding", "references", "official", "api")
doc_of = {}
if os.path.isdir(OFFICIAL):
    for fname in sorted(os.listdir(OFFICIAL)):
        if fname.endswith(".md") and fname != "README.md":
            for n in re.findall(r"^### (\w+)$", open(os.path.join(OFFICIAL, fname), encoding="utf-8").read(), re.M):
                doc_of[n] = fname

rows, section = [], "General"
for i, line in enumerate(src, 1):
    m = re.match(r"^function ([A-Za-z_][\w\.]*)\((.*)\)", line)
    if not m:
        continue
    name, params = m.group(1), m.group(2)
    flag = side(name)
    rows.append((name, params, flag, i))

if not doc_of:
    sys.exit("no official docs in references/official/api/: run python -I tools/fetch_official_docs.py first")
official = sum(1 for r in rows if r[0] in doc_of)

out = ["# Teardown API index",
       "",
       f"Generated by `tools/gen_api_index.py` from `data/script_defs.lua` (game 2.2.0, {len(rows)} functions), the bridge",
       f"probes and the official API reference ({official} of these functions are in it).",
       "",
       "Look a function up here first, then read its entry: the **Doc** column links the official",
       "documentation (arguments, return values, description, example) in `official/api/`. That folder is",
       "generated on each machine and is not in git: if it is missing, run `python -I tools/fetch_official_docs.py`.",
       "\"not in official docs\": the function exists in `script_defs.lua` but not in the published API (mostly",
       "internal or undocumented helpers); its comment, if any, is at the given line of",
       "`<Teardown>/data/script_defs.lua` (about 25 lines above the `function` line).",
       "",
       "Side column (measured, see quirks.md \"Wrong-side calls\"; the official SERVER ONLY / CLIENT ONLY tags",
       "agree with every measured one-sided function):",
       "",
       "- blank: callable from server and client code",
       "- `server`: server code only. From client code the engine stops the client half of the script",
       "- `client`: client code only. From server code the engine stops the server half of the script",
       "- `draw`: exists only inside `client.draw()` (nil everywhere else)",
       "- `internal`: raises \"function is only for internal usage\"; mods cannot use it",
       "- `missing`: documented but not present in the game",
       "- `untested`: not probed (destructive, session-level, or engine helper)",
       "",
       "| Function | Side | Doc | Line |", "|---|---|---|---|"]
for name, params, flag, line in rows:
    doc = f"[{doc_of[name][:-3]}](official/api/{doc_of[name]}#{name.lower()})" if name in doc_of else "not in official docs"
    out.append(f"| `{name}({params})` | {flag} | {doc} | {line} |")
dst = os.path.join(ROOT, "skill", "teardown-modding", "references", "api-index.md")
open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
from collections import Counter
missing_docs = sorted(set(doc_of) - {r[0] for r in rows})
print(len(rows), "functions,", official, "with official docs;", Counter(r[2] or "both" for r in rows))
if missing_docs:
    print("in the official docs but not in script_defs.lua:", ", ".join(missing_docs))
